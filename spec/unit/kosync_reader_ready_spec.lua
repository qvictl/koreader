require("commonrequire")
local saved_path = package.path
package.path = "plugins/kosync.koplugin/?.lua;" .. package.path
local Queue = require("KOSyncQueue")
local Client = require("KOSyncClient")
local KOSync = dofile("plugins/kosync.koplugin/main.lua")
package.path = saved_path
local NetworkMgr = require("ui/network/manager")
local UIManager = require("ui/uimanager")

describe("KOSync pending progress on reader ready", function()
    local tasks, online, uploads, callbacks, pulls, local_progress
    before_each(function()
        Queue:clear()
        tasks, online, uploads, callbacks, pulls = {}, {}, {}, {}, {}
        local_progress = "fresh local progress"
        stub(UIManager, "nextTick", function(_, callback) tasks[#tasks + 1] = callback end)
        stub(UIManager, "scheduleIn", function(_, _, callback) tasks[#tasks + 1] = callback end)
        stub(NetworkMgr, "runWhenOnline", function(_, callback) online[#online + 1] = callback end)
        stub(Client, "new", function()
            return { update_progress = function(_, _, _, document, _, _, _, _, _, callback)
                uploads[#uploads + 1] = { document = document, done = callback }
                callbacks[#callbacks + 1] = callback
            end }
        end)
    end)
    after_each(function()
        for _, callback in ipairs(callbacks) do callback(false) end
        UIManager.nextTick:revert()
        UIManager.scheduleIn:revert()
        NetworkMgr.runWhenOnline:revert()
        Client.new:revert()
        Queue:clear()
    end)
    local function plugin()
        return setmetatable({
            path = "plugins/kosync.koplugin", settings = { auto_sync = true, username = "synthetic", userkey = "key" },
            ui = { document = {}, getCurrentPage = function() return 1 end },
            getDocumentDigest = function() return "current-book" end,
            registerEvents = function() end, onDispatcherRegisterActions = function() end,
            getProgress = function(_, ensure_networking)
                pulls[#pulls + 1] = ensure_networking
                local_progress = "old remote progress"
            end,
        }, { __index = KOSync })
    end
    local function runTask() table.remove(tasks, 1)() end
    local function queue(document) Queue:push{ document = document, progress = "fresh" } end
    local function ready(sync)
        sync:onReaderReady()
        runTask()
    end
    it("preserves the original empty-queue pull", function()
        ready(plugin())
        assert.same({ true }, pulls)
        assert.are.equal(0, #online)
        assert.are.equal(0, #uploads)
    end)
    it("prioritizes the current document before pulling, even if another book later fails", function()
        queue("other-book")
        queue("current-book")
        ready(plugin())
        assert.are.equal(0, #pulls)
        online[1]()
        assert.are.equal("current-book", uploads[1].document)
        assert.are.equal(0, #pulls)
        uploads[1].done(true)
        assert.are.equal("other-book", uploads[2].document)
        assert.are.equal(0, #pulls)
        uploads[2].done(false)
        assert.same({ false }, pulls)
        assert.are.equal("other-book", Queue:load()[1].document)
    end)
    it("does not overwrite local progress while its upload is unfinished", function()
        queue("current-book")
        ready(plugin())
        online[1]()
        assert.are.equal(1, #uploads)
        assert.are.equal(0, #pulls)
        assert.are.equal("fresh local progress", local_progress)
    end)
    it("does not overwrite local progress when its upload fails", function()
        queue("current-book")
        ready(plugin())
        online[1]()
        uploads[1].done(false)
        assert.are.equal(0, #pulls)
        assert.are.equal("fresh local progress", local_progress)
        assert.are.equal(1, Queue:count())
    end)
    it("still pulls the current document when only another book fails", function()
        queue("other-book")
        ready(plugin())
        online[1]()
        uploads[1].done(false)
        assert.same({ false }, pulls)
        assert.are.equal(1, Queue:count())
    end)
    it("retries the current book after an already-running drain fails on another book", function()
        queue("other-book")
        queue("current-book")
        local pending
        Queue:drain(function(_, callback) pending = callback; callbacks[#callbacks + 1] = callback end)
        ready(plugin())
        online[1]()
        assert.are.equal(0, #uploads)
        assert.are.equal(1, #tasks)
        pending(false)
        runTask()
        assert.are.equal("current-book", uploads[1].document)
        uploads[1].done(true)
        uploads[2].done(false)
        assert.same({ false }, pulls)
    end)
    it("does not pull old remote progress after a NetworkConnected upload fails", function()
        queue("current-book")
        local sync = plugin()
        sync:_onNetworkConnected()
        runTask()
        uploads[1].done(false)
        assert.are.equal(0, #pulls)
        assert.are.equal("fresh local progress", local_progress)
        assert.are.equal(1, Queue:count())
    end)
    it("does not access the closed document when the online check finishes", function()
        queue("current-book")
        local sync = plugin()
        ready(sync)
        sync.ui.document = nil
        online[1]()
        assert.are.equal(0, #uploads)
        assert.are.equal(0, #pulls)
    end)
    it("stops waiting for an overlapping drain after the reader closes", function()
        queue("other-book")
        local pending
        Queue:drain(function(_, callback) pending = callback; callbacks[#callbacks + 1] = callback end)
        local sync = plugin()
        ready(sync)
        online[1]()
        sync.ui.document = nil
        runTask()
        pending(false)
        assert.are.equal(0, #uploads)
        assert.are.equal(0, #pulls)
        assert.are.equal(0, #tasks)
    end)
end)
