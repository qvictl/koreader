require("commonrequire")
local Device = require("device")
local NetworkMgr = require("ui/network/manager")
local Trapper = require("ui/trapper")
local UIManager = require("ui/uimanager")

describe("Asynchronous online checks", function()
    local workers
    before_each(function()
        workers = {}
        stub(Device, "hasWifiToggle", function() return true end)
        stub(Trapper, "dismissableRunInSubprocess", function(_, task)
            workers[#workers + 1] = { task = task, co = coroutine.running() }
            return coroutine.yield()
        end)
        stub(NetworkMgr, "isOnline", function() return true end)
        stub(NetworkMgr, "beforeWifiAction")
        stub(NetworkMgr, "isConnected", function() return false end)
    end)
    after_each(function()
        -- Settle any still-pending checks, balancing Trapper's standby inhibition.
        for _, worker in ipairs(workers) do
            if coroutine.status(worker.co) ~= "dead" then
                coroutine.resume(worker.co, false)
            end
        end
        Device.hasWifiToggle:revert()
        Trapper.dismissableRunInSubprocess:revert()
        NetworkMgr.isOnline:revert()
        NetworkMgr.beforeWifiAction:revert()
        NetworkMgr.isConnected:revert()
    end)
    local function complete(index, online, completed)
        assert.is_true(coroutine.resume(workers[index].co, completed ~= false, online))
    end

    it("defers an online action until its independent check completes", function()
        local calls = 0
        NetworkMgr:runWhenOnline(function() calls = calls + 1 end)
        assert.are.equal(0, calls)
        assert.are.equal(1, #workers)
        complete(1, true)
        assert.are.equal(1, calls)
    end)
    it("lets a recursively guarded action continue exactly once", function()
        local calls, rerun = 0
        local function action()
            rerun = NetworkMgr:willRerunWhenOnline(action)
            if rerun then return end
            calls = calls + 1
        end
        action()
        assert.is_true(rerun)
        assert.are.equal(0, calls)
        complete(1, true)
        assert.is_false(rerun)
        assert.are.equal(1, calls)
        assert.are.equal(1, #workers)
        action()
        assert.is_true(rerun)
        assert.are.equal(2, #workers)
    end)
    it("does not share a successful check with another coroutine", function()
        NetworkMgr:checkOnline(function()
            assert.is_false(NetworkMgr:willRerunWhenOnline(function() error("unexpected rerun") end))
            coroutine.yield()
        end)
        complete(1, true)
        local calls = 0
        assert.is_true(NetworkMgr:willRerunWhenOnline(function() calls = calls + 1 end))
        assert.are.equal(2, #workers)
        assert.are.equal(0, calls)
        assert.is_true(coroutine.resume(workers[1].co))
        complete(2, true)
        assert.are.equal(1, calls)
    end)
    it("does not invoke actions or reconnect after cancellation, even with a late result", function()
        local callback = spy.new(function() end)
        NetworkMgr:runWhenOnline(callback)
        complete(1, true, false)
        assert.spy(callback).was_not_called()
        assert.stub(NetworkMgr.beforeWifiAction).was_not_called()
        assert.is_false(coroutine.resume(workers[1].co, true, true))
        assert.spy(callback).was_not_called()
    end)
    it("retains the reconnect callback when disconnected", function()
        local callback = function() end
        NetworkMgr:runWhenOnline(callback)
        complete(1, false)
        assert.stub(NetworkMgr.beforeWifiAction).was_called_with(NetworkMgr, callback)
    end)
    it("avoids a recursive reconnect callback when connected but offline", function()
        NetworkMgr.isConnected.returns(true)
        NetworkMgr:runWhenOnline(function() error("offline action ran") end)
        complete(1, false)
        assert.stub(NetworkMgr.beforeWifiAction).was_called_with(NetworkMgr)
    end)
    it("preserves immediate behavior on platforms without a Wi-Fi toggle", function()
        Device.hasWifiToggle.returns(false)
        local callback = spy.new(function() end)
        NetworkMgr:runWhenOnline(callback)
        assert.spy(callback).was_called(1)
        assert.is_false(NetworkMgr:willRerunWhenOnline(callback))
        assert.are.equal(0, #workers)
    end)
    it("defers Wallabag queue or upload decisions until checking finishes", function()
        local Wallabag = dofile("plugins/wallabag.koplugin/main.lua")
        local article = "https://example.invalid/synthetic-article"
        local queued, added
        local plugin = setmetatable({
            addToOfflineQueue = function(_, url) queued = url end,
            addArticle = function(_, url) added = url; return true end,
        }, { __index = Wallabag })
        stub(UIManager, "show")
        plugin:onAddWallabagArticle(article)
        assert.is_nil(queued)
        assert.is_nil(added)
        complete(1, false)
        assert.are.equal(article, queued)
        plugin:onAddWallabagArticle(article)
        complete(2, true)
        assert.are.equal(article, added)
        UIManager.show:revert()
    end)
end)
